    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        try {
            model.Producto p = new model.Producto();
            p.setNombre(txtNombre.getText());
            p.setPrecio(Double.parseDouble(txtPrecio.getText()));
            p.setCantidad(Integer.parseInt(txtCantidad.getText()));
            p.setCategoria((model.Categoria) cbCategoria.getSelectedItem());
    
            dao.ProductoDAO dao = new dao.ProductoDAO();
            if(dao.insertar(p)) {
                javax.swing.JOptionPane.showMessageDialog(this, "Producto guardado con éxito");
                cargarTabla(); 
            }
            } catch (Exception e) {
                javax.swing.JOptionPane.showMessageDialog(this, "Error: Revisa que el precio y cantidad sean números");
            }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:
        int fila = tblProductos.getSelectedRow();
        if (fila >= 0) {
        try {
            model.Producto p = new model.Producto();
            p.setIdProducto(Integer.parseInt(tblProductos.getValueAt(fila, 0).toString()));
            p.setNombre(txtNombre.getText());
            p.setPrecio(Double.parseDouble(txtPrecio.getText()));
            p.setCantidad(Integer.parseInt(txtCantidad.getText()));
            p.setCategoria((model.Categoria) cbCategoria.getSelectedItem());
        
            dao.ProductoDAO dao = new dao.ProductoDAO();
            if (dao.actualizar(p)) {
                javax.swing.JOptionPane.showMessageDialog(this, "Producto actualizado con éxito");
                cargarTabla(); 
            }
            } catch (Exception e) {
                javax.swing.JOptionPane.showMessageDialog(this, "Error: Revisa los campos numéricos");
            }
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Primero selecciona un producto de la tabla para actualizarlo");
            }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        int fila = tblProductos.getSelectedRow();
        if (fila >= 0) {
        int confirmacion = javax.swing.JOptionPane.showConfirmDialog(this, 
            "¿Estás seguro de que deseas eliminar este producto?", 
            "Confirmar eliminación", 
            javax.swing.JOptionPane.YES_NO_OPTION);
            
        if (confirmacion == javax.swing.JOptionPane.YES_OPTION) {
            int id = Integer.parseInt(tblProductos.getValueAt(fila, 0).toString());
            dao.ProductoDAO dao = new dao.ProductoDAO();
            if (dao.eliminar(id)) {
                javax.swing.JOptionPane.showMessageDialog(this, "Producto eliminado");
                cargarTabla();
            }
        }
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Selecciona un producto de la tabla para eliminarlo");
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

