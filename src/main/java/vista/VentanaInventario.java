private void cargarTabla() {
        javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tblProductos.getModel();
        modelo.setRowCount(0); // Limpia la tabla antes de cargar
        dao.ProductoDAO dao = new dao.ProductoDAO();
        for (model.Producto p : dao.listar()) {
            modelo.addRow(new Object[]{
                p.getIdProducto(), 
                p.getNombre(), 
                p.getPrecio(), 
                p.getCantidad(), 
                p.getCategoria().getNombre()
            });
        }
    }

